/**
 * Returns assessment questions arranged in the given questionOrder.
 * If order is not provided or invalid, returns default canonical sequence.
 */
export function getOrderedQuestions(order?: number[] | null): typeof assessmentData {
  if (!order || !Array.isArray(order) || order.length !== assessmentData.length) {
    return assessmentData;
  }
  const map = new Map<number, (typeof assessmentData)[0]>();
  for (const q of assessmentData) {
    map.set(q.id, q);
  }
  const ordered: typeof assessmentData = [];
  for (const id of order) {
    const q = map.get(id);
    if (q) ordered.push(q);
  }
  return ordered.length === assessmentData.length ? ordered : assessmentData;
}

export default assessmentData;

